window.CY = window.CY || {};

(function () {
  var STORE = 'cy-lang';
  var SUPPORTED = ['fr', 'en', 'zh'];

  function read() {
    try {
      var s = localStorage.getItem(STORE);
      if (s && SUPPORTED.indexOf(s) > -1) return s;
    } catch (e) {}
    return 'fr';
  }

  CY.lang = read();

  CY.t = function (key) {
    var d = CY_I18N[CY.lang] || CY_I18N.fr;
    return key in d ? d[key] : (CY_I18N.fr[key] || key);
  };

  /* pick the right field off a {fr,en,zh} object */
  CY.pick = function (obj) {
    if (!obj) return '';
    return obj[CY.lang] || obj.fr || '';
  };

  CY.applyI18n = function (root) {
    var scope = root || document;

    scope.querySelectorAll('[data-i18n]').forEach(function (el) {
      el.textContent = CY.t(el.getAttribute('data-i18n'));
    });
    scope.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      el.innerHTML = CY.t(el.getAttribute('data-i18n-html'));
    });
    scope.querySelectorAll('[data-i18n-ph]').forEach(function (el) {
      el.setAttribute('placeholder', CY.t(el.getAttribute('data-i18n-ph')));
    });
    scope.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
      el.setAttribute('aria-label', CY.t(el.getAttribute('data-i18n-aria')));
    });
  };

  CY.setLang = function (lang) {
    if (SUPPORTED.indexOf(lang) < 0 || lang === CY.lang) return;
    CY.lang = lang;
    try { localStorage.setItem(STORE, lang); } catch (e) {}
    document.documentElement.setAttribute('lang', lang === 'zh' ? 'zh-Hans' : lang);
    document.body.classList.toggle('lang-zh', lang === 'zh');
    CY.applyI18n();
    document.querySelectorAll('.lang button').forEach(function (b) {
      b.classList.toggle('on', b.dataset.lang === lang);
    });
    document.dispatchEvent(new CustomEvent('cy:lang', { detail: lang }));
  };

  /* price formatting follows the restaurant's market, not the UI language */
  CY.price = function (p) {
    if (p === null || p === undefined) return null;
    return p.toFixed(2).replace('.', ',') + ' €';
  };

  CY.initLang = function () {
    document.documentElement.setAttribute('lang', CY.lang === 'zh' ? 'zh-Hans' : CY.lang);
    document.body.classList.toggle('lang-zh', CY.lang === 'zh');
    document.querySelectorAll('.lang button').forEach(function (b) {
      b.classList.toggle('on', b.dataset.lang === CY.lang);
      b.addEventListener('click', function () { CY.setLang(b.dataset.lang); });
    });
    CY.applyI18n();
  };
})();
